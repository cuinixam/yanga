def test_create_variant_cmake_file(env: ExecutionContext) -> None:
    output_dir = env.project_root_dir / "output"
    write_file(
        Path(env.project_root_dir, "tools/my_cmake_generator.py"),
        """
from pathlib import Path
from typing import Dict, List

from yanga_core.domain.execution_context import (
    ExecutionContext,
)

from yanga.cmake.cmake_backend import (
    CMakeComment,
    CMakeElement,
)
from yanga.cmake.generator import CMakeGenerator


class MyCMakeGenerator(CMakeGenerator):
    def __init__(self, execution_context: ExecutionContext, output_dir: Path, config: Dict) -> None:
        super().__init__(execution_context, output_dir, config)

    def generate(self) -> list[CMakeElement]:
        elements: list[CMakeElement] = []
        elements.append(CMakeComment(f"Generated by {self.__class__.__name__}"))
        return elements

""",
    )
    env.platform = PlatformConfig(
        name="MockPlatfrom",
        generators=[
            PipelineStepConfig(
                step="MyCMakeGenerator",
                file="tools/my_cmake_generator.py",
            )
        ],
    )
    generator = CMakeBuildSystemGenerator(env, output_dir)
    cmake_file = generator.create_variant_cmake_file()
    assert cmake_file.path == output_dir / "variant.cmake"
    assert "# Generated by MyCMakeGenerator" == assert_element_of_type(cmake_file.content, CMakeComment, lambda comment: "MyCMakeGenerator" in comment.to_string()).to_string()


def test_create_variant_cmake_file_includes_cmake_configs_last(env: ExecutionContext) -> None:
    cast(Mock, env.spl_paths).locate_artifact.side_effect = lambda artifact, _search_paths: env.project_root_dir / artifact
    env.platform = PlatformConfig(
        name="zephyr",
        configs=[
            ConfigFile(id="cmake", file=Path("platforms/zephyr/app.cmake")),
            ConfigFile(id="cmake", file=Path("platforms/zephyr/extra.cmake")),
        ],
    )
    content = CMakeBuildSystemGenerator(env, env.project_root_dir / "output").create_variant_cmake_file().content
    includes = [element.to_string() for element in content if isinstance(element, CMakeInclude)]
    assert includes == [
        f"include({(env.project_root_dir / 'platforms/zephyr/app.cmake').as_posix()})",
        f"include({(env.project_root_dir / 'platforms/zephyr/extra.cmake').as_posix()})",
    ]
    assert [element.to_string() for element in content[-2:]] == includes


def test_create_variant_cmake_file_rejects_inline_cmake_config(env: ExecutionContext) -> None:
    env.platform = PlatformConfig(name="zephyr", configs=[ConfigFile(id="cmake", content={"not": "a file"})])
    with pytest.raises(UserNotificationException, match="cmake"):
        CMakeBuildSystemGenerator(env, env.project_root_dir / "output").create_variant_cmake_file()
